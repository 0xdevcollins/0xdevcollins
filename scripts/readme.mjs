// Writes README.md from profile.config.mjs, so alt text always matches what each image says.
//   node scripts/readme.mjs   (render.mjs also runs this after a full render)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { person, products, more, stack, contacts } from '../profile.config.mjs';
import { usedIn } from '../design/cards.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const attr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const list = (a) => (a.length > 1 ? `${a.slice(0, -1).join(', ')} and ${a.at(-1)}` : a[0]);

// Light image by default, dark one when the viewer's GitHub theme is dark.
// Cards are WebP when the renderer had cwebp, PNG otherwise.
const cardExt = (id) => (fs.existsSync(path.join(root, 'assets', 'dark', `${id}.webp`)) ? 'webp' : 'png');
const pic = (id, alt, width = '100%', svg = false) => {
  const [dark, light] = svg ? [`assets/${id}-dark.svg`, `assets/${id}-light.svg`] : [`assets/dark/${id}.${cardExt(id)}`, `assets/light/${id}.${cardExt(id)}`];
  return `<picture><source media="(prefers-color-scheme: dark)" srcset="${dark}"><img src="${light}" alt="${attr(alt)}" width="${width}"></picture>`;
};
const link = (url, inner) => `<a href="${url}">${inner}</a>`;
const block = (...items) => `<p align="center">\n  ${items.join('\n  ')}\n</p>`;

export function buildReadme() {
  const productAlt = (p) =>
    `${p.name}: ${p.kicker}. ${p.body}${p.rows ? ' ' + p.rows.map(([k, v]) => `${k}: ${v}.`).join(' ') : ''} Built with ${list(p.tags)}.`;

  const parts = [
    `<!-- Generated by scripts/readme.mjs from profile.config.mjs. Edit those, then run npm run render. -->`,
    block(pic('hero',
      `${person.first} ${person.last}. ${person.role}. ${person.discipline} developer in ${person.location}. ${person.line} Now shipping: ${products.map((p) => `${p.name}, ${p.index.toLowerCase()}`).join('; ')}.`)),
    ...products.map((p) => block(link(p.url, pic(p.id, productAlt(p))))),
    block(...more.map((m) => link(m.url, pic(`more-${m.id}`, `${m.name}, ${m.label === 'Lab' ? 'lab build' : 'Thirtn product'}: ${m.body} Built with ${list(m.tags)}.`, '49%')))),
    block(pic('stack', `Bill of materials. ${stack.map(([layer, parts]) => { const u = usedIn(parts).map((it) => it.name); return `${layer}: ${list(parts)}${u.length ? `, used in ${list(u)}` : ''}.`; }).join(' ')}`)),
    block(pic('stats', 'GitHub activity for 0xdevcollins: contributions and pull requests in the last 12 months with a weekly chart, current and all-time streaks, the latest merged pull requests in public repos, and language share. Refreshed every 6 hours.', '100%', true)),
    block(...contacts.map((c) => link(c.url, pic(`c-${c.id}`, `${c.label}: ${c.handle}`, '32%')))),
  ];
  return parts.join('\n\n') + '\n';
}

if (path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, 'README.md'), buildReadme());
  console.log('wrote README.md');
}
